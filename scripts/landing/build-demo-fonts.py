# BUILD DEMO FONTS: writes public/landing-demos/demo-fonts.css and the small icon
# fonts it uses, holding only the Phosphor icons the landing demos mention.
#
# WHY: every demo is its own page in a frame. The full Phosphor sets are 416 KB of
# CSS and 443 KB of fonts for about 30 icons, and they hold back each demo's first paint.
#
# RUN AGAIN after a demo gains an icon, or that icon shows as an empty box:
#   pip install fonttools brotli
#   python scripts/landing/build-demo-fonts.py
#
# The full sets stay in public/landing-demos/phosphor as the source for this script.

import re
import sys
from pathlib import Path

from fontTools import subset

DEMOS = Path(__file__).resolve().parents[2] / "public" / "landing-demos"
SOURCES = ["concept-*.html", "live-demo.js", "glossary-demo.js"]
OUTPUT_DIR = DEMOS / "phosphor" / "subset"

# weight folder, CSS class, font file, font family
WEIGHTS = [
    ("regular", "ph", "Phosphor.woff2", "Phosphor"),
    ("duotone", "ph-duotone", "Phosphor-Duotone.woff2", "Phosphor-Duotone"),
    ("fill", "ph-fill", "Phosphor-Fill.woff2", "Phosphor-Fill"),
]

# The self-hosted text fonts (Geist from Google Fonts, latin, under the SIL Open Font License)
TEXT_FONTS = """@font-face {
  font-family: "Geist";
  src: url("fonts/Geist-latin.woff2") format("woff2");
  font-weight: 400 600;
  font-display: swap;
}
@font-face {
  font-family: "Geist Mono";
  src: url("fonts/GeistMono-latin.woff2") format("woff2");
  font-weight: 400;
  font-display: swap;
}
"""

BASE_RULES = """.ph, .ph-duotone, .ph-fill {
  speak: never;
  font-style: normal;
  font-weight: normal;
  font-variant: normal;
  text-transform: none;
  line-height: 1;
  letter-spacing: 0;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}
"""


# Every icon the demos name, as "ph-file-pdf", without the weight classes
def used_icons() -> list[str]:
    text = "".join(path.read_text(encoding="utf-8") for pattern in SOURCES for path in DEMOS.glob(pattern))
    named = set(re.findall(r"\bph-[a-z0-9]+(?:-[a-z0-9]+)*", text))
    return sorted(named - {"ph-duotone", "ph-fill"})


# The rules for these icons in one weight's stylesheet, and the characters they draw
def rules_for(css: str, weight_class: str, icons: list[str]) -> tuple[list[str], set[int]]:
    rules: list[str] = []
    codepoints: set[int] = set()
    for icon in icons:
        pattern = rf"\.{re.escape(weight_class)}\.{re.escape(icon)}:(?:before|after) \{{[^}}]*\}}"
        found = re.findall(pattern, css)
        if not found:
            sys.exit(f"{icon} is not in the {weight_class} set; check the demo that names it.")
        rules.extend(" ".join(rule.split()) for rule in found)
        codepoints.update(int(code, 16) for rule in found for code in re.findall(r'content: "\\([0-9a-f]+)"', rule))
    return rules, codepoints


# Writes a font holding only these characters
def write_subset(source: Path, target: Path, codepoints: set[int]) -> None:
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = []
    options.notdef_outline = True
    font = subset.load_font(str(source), options)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    subset.save_font(font, str(target), options)


def main() -> None:
    icons = used_icons()
    OUTPUT_DIR.mkdir(exist_ok=True)
    sections = [
        "/* Generated by scripts/landing/build-demo-fonts.py; edit that, not this file. */",
        TEXT_FONTS,
        BASE_RULES,
    ]
    for folder, weight_class, font_file, family in WEIGHTS:
        css = (DEMOS / "phosphor" / folder / "style.css").read_text(encoding="utf-8")
        rules, codepoints = rules_for(css, weight_class, icons)
        write_subset(DEMOS / "phosphor" / folder / font_file, OUTPUT_DIR / font_file, codepoints)
        sections.append(
            f'@font-face {{ font-family: "{family}"; src: url("phosphor/subset/{font_file}") format("woff2"); font-display: block; }}\n'
            f'.{weight_class} {{ font-family: "{family}" !important; }}\n' + "\n".join(rules) + "\n"
        )
    (DEMOS / "demo-fonts.css").write_text("\n".join(sections), encoding="utf-8", newline="\n")
    print(f"{len(icons)} icons")


if __name__ == "__main__":
    main()
